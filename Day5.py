# Slicing Strings
b = "Hello, World!"
print(b[2:5])
b = "Hello, World!"
print(b[:5])
#Modify Strings
a = "Hello, World!"
print(a.upper())
print(a.lower())
#Remove Whitespace
a = " Hello, World! "
print(a.strip()) # returns "Hello, World!"
#String Concatenation
a = "Tamim"
b = "Ahamed"
c = a + b
print(c)
a = "Tamim"
b = "Ahamed"
c = a + " " + b
print(c)

